"""Aggregate CEXP04 seeds {42,123,7} → mean±std. Read-only over result JSONs."""
import json
import statistics as st
from pathlib import Path

BASE = Path(r"d:\LLM-IDS_RAG\Experiment_Lab\conf_track\Results\Scaled_Eval")
FILES = {
    42: BASE / "CEXP04_42Seeds" / "cexp04_results_cexp04_scaled_seed42_N499_RECOVERED.json",
    123: BASE / "CEXP04_ScaledEval_1223Seeds" / "cexp04_results_cexp04_scaled_seed123_N499.json",
    7: BASE / "CEXpP04_7_Seed" / "CEXP04_Scaled_Eval_7seed" / "cexp04_results_cexp04_scaled_seed7_N499.json",
}
OUT_DIR = BASE / "CEXP04_Aggregate_3seeds"
OUT_DIR.mkdir(parents=True, exist_ok=True)
NOTES = Path(r"d:\LLM-IDS_RAG\Paper_Writing\conf\round2_notes\01_CEXP04_Scaled_Eval\AGGREGATE.md")

data = {s: json.loads(p.read_text(encoding="utf-8")) for s, p in FILES.items()}
seeds = [42, 123, 7]


def ms(vals):
    """mean ± sample std (N-1). Use sample std for paper mean±std over seeds."""
    vals = [v for v in vals if v is not None]
    m = st.mean(vals)
    s = st.stdev(vals) if len(vals) > 1 else 0.0  # sample std, not pstdev
    return round(m, 4), round(s, 4)


def fmt(vals):
    m, s = ms(vals)
    return f"{m:.4f}±{s:.4f}"


# ---- Clean (seed42 recovered uses *_multi suffix) ----
def clean_get(seed, kind):
    c = data[seed]["clean"]
    for k in (kind, kind + "_multi"):
        if k in c:
            return c[k]
    raise KeyError(kind)

clean = {}
for key in ("undefended", "defended_full"):
    clean[key] = {
        "f1": ms([clean_get(s, key)["f1"] for s in seeds]),
        "fpr": ms([clean_get(s, key)["fpr"] for s in seeds]),
    }

# ---- Poison sweep ----
rates = [0.01, 0.05, 0.1, 0.2, 0.3]
poison = []
for r in rates:
    def row(seed):
        for pr in data[seed]["poison_results"]:
            if abs(pr["poison_rate"] - r) < 1e-9:
                return pr
        return None
    rows = {s: row(s) for s in seeds}
    poison.append({
        "poison_rate": r,
        "undef_f1": ms([rows[s]["undefended"]["f1"] for s in seeds]),
        "undef_fpr": ms([rows[s]["undefended"]["fpr"] for s in seeds]),
        "def_f1": ms([rows[s]["defended_full"]["f1"] for s in seeds]),
        "def_fpr": ms([rows[s]["defended_full"]["fpr"] for s in seeds]),
        "R": ms([rows[s]["recovery_R"] for s in seeds]),
        "per_seed_R": {s: rows[s]["recovery_R"] for s in seeds},
    })

# ---- Injection ----
def inj_row(seed, mode, pid):
    for ir in data[seed]["injection_results"]:
        if ir["mode"] == mode and ir["payload_id"] == pid:
            return ir
    return None

payloads = ["P1", "P2", "P3", "P4", "P5"]
injection = {}
for mode in ("multi", "single"):
    injection[mode] = []
    for pid in payloads:
        rows = {s: inj_row(s, mode, pid) for s in seeds}
        injection[mode].append({
            "payload_id": pid,
            "success": ms([rows[s]["injection_success"] for s in seeds]),
            "f1_injected": ms([rows[s]["f1_injected"] for s in seeds]),
            "f1_defended": ms([rows[s]["f1_defended"] for s in seeds]),
            "R_D3": ms([rows[s]["R_D3"] for s in seeds]),
        })

# ---- Latency ----
lat_stages = ["embed", "retrieve", "defense", "llm", "e2e"]
latency = {stg: ms([data[s]["latency"]["stages_ms"][stg]["mean"] for s in seeds]) for stg in lat_stages}

agg = {
    "experiment": "CEXP04_Scaled_Eval_aggregate",
    "seeds": seeds,
    "n_eval": 499,
    "clean": clean,
    "poison_results": poison,
    "injection_results": injection,
    "latency_ms": latency,
}
(OUT_DIR / "cexp04_aggregate_3seeds.json").write_text(json.dumps(agg, indent=2), encoding="utf-8")

# ---- Markdown ----
L = []
L.append("# CEXP04 — Aggregate across seeds {42, 123, 7} (mean±std)\n")
L.append("**N=499 each · macro-F1 · defended = full D1+D2+D3 · R = F1/clean-undef-F1**\n")
L.append("Auto-generated by `_aggregate_seeds.py` from the three seed JSONs. Do not hand-edit numbers.\n")

L.append("\n## Clean\n")
L.append("| Setting | F1 | FPR |")
L.append("|---------|-----|-----|")
L.append(f"| Undefended (k=5) | {fmt([clean_get(s,'undefended')['f1'] for s in seeds])} | {fmt([clean_get(s,'undefended')['fpr'] for s in seeds])} |")
L.append(f"| Defended full | {fmt([clean_get(s,'defended_full')['f1'] for s in seeds])} | {fmt([clean_get(s,'defended_full')['fpr'] for s in seeds])} |")

L.append("\n## Poisoning (mean±std, n=3 seeds)\n")
L.append("| Rate | Undef F1 | Def F1 | Undef FPR | Def FPR | R |")
L.append("|------|----------|--------|-----------|---------|---|")
for p in poison:
    L.append(
        f"| {int(p['poison_rate']*100)}% "
        f"| {p['undef_f1'][0]:.4f}±{p['undef_f1'][1]:.4f} "
        f"| {p['def_f1'][0]:.4f}±{p['def_f1'][1]:.4f} "
        f"| {p['undef_fpr'][0]:.4f}±{p['undef_fpr'][1]:.4f} "
        f"| {p['def_fpr'][0]:.4f}±{p['def_fpr'][1]:.4f} "
        f"| {p['R'][0]:.3f}±{p['R'][1]:.3f} |"
    )

L.append("\n### Per-seed R (transparency)\n")
L.append("| Rate | seed42 | seed123 | seed7 |")
L.append("|------|--------|---------|-------|")
for p in poison:
    ps = p["per_seed_R"]
    L.append(f"| {int(p['poison_rate']*100)}% | {ps[42]:.3f} | {ps[123]:.3f} | {ps[7]:.3f} |")

for mode in ("multi", "single"):
    L.append(f"\n## Injection — {mode}-doc (mean±std)\n")
    L.append("| Payload | Success | F1 inj | F1 def | R_D3 |")
    L.append("|---------|---------|--------|--------|------|")
    for r in injection[mode]:
        L.append(
            f"| {r['payload_id']} "
            f"| {r['success'][0]:.3f}±{r['success'][1]:.3f} "
            f"| {r['f1_injected'][0]:.4f}±{r['f1_injected'][1]:.4f} "
            f"| {r['f1_defended'][0]:.4f}±{r['f1_defended'][1]:.4f} "
            f"| {r['R_D3'][0]:.3f}±{r['R_D3'][1]:.3f} |"
        )

L.append("\n## Latency (clean defended, ms, mean±std of per-seed means)\n")
L.append("| Stage | ms |")
L.append("|-------|-----|")
for stg in lat_stages:
    L.append(f"| {stg} | {latency[stg][0]:.2f}±{latency[stg][1]:.2f} |")

L.append("\n## Paper talking points\n")
L.append("- Poison recovery R decreases monotonically with rate and is **stable across seeds** (small std) → supports mean±std reporting (Major 2).")
L.append("- Multi-doc injection success ≈1–2% (all seeds); **single-doc 34–60%** → the harder setting Major 4 wanted; report both.")
L.append("- Single-doc `F1_def==F1_inj` every seed (nothing to rerank) — state as a known limit of demotion, not a bug.")
L.append("- Latency LLM-dominated (~1.7–2.0 s e2e); D1–D3 overhead ~5 ms → Efficiency goal met.")
L.append("- Clean absolute F1 ~0.26 across seeds → keep defense-first framing.\n")

NOTES.write_text("\n".join(L), encoding="utf-8")
print("Wrote", OUT_DIR / "cexp04_aggregate_3seeds.json")
print("Wrote", NOTES)
print("\nPoison R mean±std:")
for p in poison:
    print(f"  {int(p['poison_rate']*100):>2}%  R={p['R'][0]:.3f}±{p['R'][1]:.3f}  undefF1={p['undef_f1'][0]:.4f}  defF1={p['def_f1'][0]:.4f}")
